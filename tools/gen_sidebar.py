others = sorted(set(files) - assigned)

lines = ["* [🏠 首页](home.md)", ""]
total = 0
for cat, items in CATEGORIES.items():
    present = [it for it in items if it in files]
    if not present:
        continue
    lines.append(f"* {cat}")
    for it in present:
        rel = os.path.relpath(os.path.join(KB, it + ".md"), ROOT).replace(os.sep, "/")
        lines.append(f"  * [{it}]({rel})")
        total += 1
    lines.append("")

